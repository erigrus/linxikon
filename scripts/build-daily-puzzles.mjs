import {readFile, writeFile} from 'node:fs/promises';
import {boardPath, LINK_THRESHOLD, links, loadLexicon, normalize, PAIRS} from '../engine.js';

const root = new URL('../', import.meta.url);
const OUTPUT_SIZE = 2048;
const MAX_ENDPOINT_SIMILARITY = .10;
const MIN_PATH_LENGTH = 4;
const MIN_HINT_LINK_STRENGTH = .54;
const MAX_PATH_LENGTH = 6;
const RECENT_DAYS = 7;
const START_DATE = '2026-11-21';

const lexicon = await loadLexicon(undefined, async path => {
  const bytes = await readFile(new URL(path.split('?')[0], root));
  return {
    ok: true,
    json: async () => JSON.parse(bytes),
    arrayBuffer: async () => Uint8Array.from(bytes).buffer,
  };
});

// Draw endpoints from familiar nouns in the existing editorial vocabulary.
const vocabulary = await readFile(new URL('data/associations.txt', root), 'utf8');
const terms = vocabulary.trim().split(/\s+/);
const eligible = word => {
  const normalized = normalize(word);
  return lexicon.has(normalized) && lexicon.canonical(normalized) === normalized;
};
const endpoints = [...new Set(terms.filter(word => /^[A-ZÄÖÜ][a-zäöüß]{2,17}$/.test(word)).filter(eligible).map(normalize))];
const words = [...new Set([...endpoints, ...terms.filter(eligible).map(normalize)])];
const neighbors = words.map(() => []);
const playableNeighbors = words.map(() => new Set());

for (let i = 0; i < words.length; i++) {
  for (let j = i + 1; j < words.length; j++) {
    const score = lexicon.score(words[i], words[j]);
    if (score >= LINK_THRESHOLD) {
      playableNeighbors[i].add(j);
      playableNeighbors[j].add(i);
    }
    if (score >= MIN_HINT_LINK_STRENGTH) {
      neighbors[i].push({index: j, score});
      neighbors[j].push({index: i, score});
    }
  }
}

const pairKey = (a, b) => [a, b].sort().join('|');
const oldPairs = new Set(PAIRS.map(([a, b]) => pairKey(a, b)));
const candidates = [];
for (let start = 0; start < endpoints.length; start++) {
  // Breadth-first search finds the shortest path. For equal lengths, keep the
  // strongest path, just as the board does when showing a solved puzzle.
  const paths = new Map([[start, {distance: 0, parent: null, strength: 0}]]);
  const queue = [start];
  for (const word of queue) {
    const {distance, strength} = paths.get(word);
    if (distance >= MAX_PATH_LENGTH - 1) continue;
    for (const {index, score} of neighbors[word]) {
      const known = paths.get(index);
      const next = {distance: distance + 1, parent: word, strength: strength + score};
      if (!known) queue.push(index);
      if (!known || (known.distance === next.distance && known.strength < next.strength)) {
        paths.set(index, next);
      }
    }
  }
  for (let end = start + 1; end < endpoints.length; end++) {
    const path = paths.get(end);
    if (!path || path.distance < MIN_PATH_LENGTH - 1) continue;
    const a = words[start], b = words[end];
    if (oldPairs.has(pairKey(a, b)) || lexicon.score(a, b) >= MAX_ENDPOINT_SIMILARITY) continue;
    if ([...playableNeighbors[start]].some(word => playableNeighbors[end].has(word))) continue;
    const route = [];
    for (let index = end; index !== null; index = paths.get(index).parent) route.unshift(words[index]);
    const board = [a, b, ...route.slice(1, -1)];
    if (boardPath(board, links(board, lexicon)).length === route.length) candidates.push(route);
  }
}

let seed = 0x73656d61;
function nextIndex(length) {
  seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
  return Math.floor(seed * length / 2 ** 32);
}
for (let i = candidates.length - 1; i > 0; i--) {
  const j = nextIndex(i + 1);
  [candidates[i], candidates[j]] = [candidates[j], candidates[i]];
}

const routes = [];
const lastPlayed = new Map();
for (const route of candidates) {
  const a = route[0], b = route.at(-1);
  const earliestRecent = routes.length - RECENT_DAYS;
  if ((lastPlayed.get(a) ?? -Infinity) >= earliestRecent ||
      (lastPlayed.get(b) ?? -Infinity) >= earliestRecent) continue;
  // Reverse some routes so the orientation isn't tied to dictionary order.
  routes.push(nextIndex(2) ? route : route.slice().reverse());
  lastPlayed.set(a, routes.length - 1);
  lastPlayed.set(b, routes.length - 1);
  if (routes.length === OUTPUT_SIZE) break;
}
if (routes.length < OUTPUT_SIZE) {
  throw new Error(`Only ${routes.length} valid daily puzzles found`);
}

const file = new URL('data/daily/catalog-v1.js', root);
await writeFile(file, `// Generated by scripts/build-daily-puzzles.mjs. Keep this schedule stable.\nexport const DAILY_START = '${START_DATE}';\nexport const MAX_ENDPOINT_SIMILARITY = ${MAX_ENDPOINT_SIMILARITY};\nexport const DAILY_ROUTES = [\n${routes.map(route => '  '+JSON.stringify(route)).join(',\n')}\n];\n`);
console.log(`Generated ${routes.length} daily puzzles from ${endpoints.length} nouns and ${words.length} total words.`);
